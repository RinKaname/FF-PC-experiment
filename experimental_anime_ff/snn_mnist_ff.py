from torch.optim import AdamW
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.optim import AdamW
from torch.utils.data import DataLoader
from torchvision.datasets import MNIST
from torchvision.transforms import Compose, Grayscale, ToTensor, Normalize, Lambda
import snntorch as snn
import matplotlib.pyplot as plt
from tqdm import tqdm
from safetensors.torch import save_model

# Setup device
device = torch.device("cuda") if torch.cuda.is_available() else torch.device("cpu")
print(f"Using device: {device}")

# Dataset transforms
transform = Compose([
    Grayscale(),
    ToTensor(),
    Normalize((0,), (1,)),
    Lambda(lambda x: torch.flatten(x))
])

# Load datasets
mnist_train = MNIST('./data/', train=True, download=True, transform=transform)
train_loader = DataLoader(mnist_train, batch_size=128, shuffle=True)

mnist_test = MNIST('./data/', train=False, download=True, transform=transform)
test_loader = DataLoader(mnist_test, batch_size=128, shuffle=False)

# --- HELPER FUNCTION ---
def overlay_y_on_x(x, y):
    """Replace the first 10 pixels of data [x] with one-hot-encoded label [y]"""
    x_ = x.clone()
    x_[:, :10] *= 0.0  # zero out the first 10 pixels of input data
    x_[range(x.shape[0]), y] = x.max()  # the y-label 'activates' the corresponding pixel
    return x_

# --- NETWORK ARCHITECTURE ---
class LeakyLayer(nn.Linear):
    def __init__(self, in_features, out_features, activation, bias=False):
        super().__init__(in_features, out_features, bias=bias)

        if activation == "lif":
            self.activation = snn.Leaky(beta=0.8)
            self.lif = True
        else:
            self.activation = nn.ReLU()
            self.lif = False

        self.opt = AdamW(self.parameters(), lr=0.005)
        self.threshold = 1.0

        # Learn from each batch once instead of memorizing a single batch.
        self.num_epochs = 1

    def forward(self, x):
        if self.lif == True:
            mem = self.activation.init_leaky()

        x_direction = x / (torch.norm(x, p=2, dim=1, keepdim=True) + 1e-4)
        weighted_input = torch.mm(x_direction, self.weight.T.to(device))

        if self.lif == True:
            spk, potential = self.activation(weighted_input, mem)
        else:
            potential = self.activation(weighted_input)

        return potential

    def train_layer(self, x_pos, x_neg):
        tot_loss = []
        for _ in range(self.num_epochs):
            g_pos = self.forward(x_pos).pow(2).mean(1)
            g_neg = self.forward(x_neg).pow(2).mean(1)

            loss = F.softplus(torch.cat([-g_pos + self.threshold, g_neg - self.threshold])).mean()

            self.opt.zero_grad()
            loss.backward()
            self.opt.step()

            # Prevents OOM memory crash over 60k images.
            tot_loss.append(loss.detach().item())

        output = self.forward(x_pos).detach(), self.forward(x_neg).detach()
        return (output, tot_loss)

class Net(nn.Module):
    def __init__(self, dims, activation):
        super().__init__()
        # We create Layer 1 and Layer 2 dynamically based on the 'dims' list.
        # Since we pass dims=[784, 500, 500] in the main block, this loop runs twice:
        # 1. d=0 -> LeakyLayer(dims[0], dims[1]) -> LeakyLayer(784, 500)  [This is Layer 1]
        # 2. d=1 -> LeakyLayer(dims[1], dims[2]) -> LeakyLayer(500, 500)  [This is Layer 2]
        self.layers = nn.ModuleList([
            LeakyLayer(dims[d], dims[d + 1], activation) for d in range(len(dims) - 1)
        ])

    def predict(self, x):
        goodness_per_label = []
        for label in range(10):
            h = overlay_y_on_x(x, label)
            goodness = []

            for layer in self.layers:
                h = layer(h)
                goodness.append(h.pow(2).mean(1))

            goodness_per_label.append(sum(goodness).unsqueeze(1))

        goodness_per_label = torch.cat(goodness_per_label, 1)
        return goodness_per_label.argmax(1)

    def train_network(self, x_pos, x_neg):
        h_pos, h_neg = x_pos, x_neg
        layer_losses = []
        # This loop trains each layer sequentially (greedy layer-wise learning).
        # Iteration 1: Trains Layer 1 using the raw input images (h_pos/h_neg start as x_pos/x_neg).
        # Iteration 2: Trains Layer 2 using the outputs (potentials) generated by Layer 1.
        for i, layer in enumerate(self.layers):
            outputs, loss = layer.train_layer(h_pos, h_neg)
            h_pos, h_neg = outputs
            layer_losses.append(loss)
        return layer_losses

# --- MAIN EXECUTION ---
if __name__ == "__main__":
    # Initialize the network
    torch.manual_seed(123)

    # The 'dims' array defines the network structure:
    # 784 = Input pixels (28x28 image)
    # 500 = Layer 1 output neurons
    # 500 = Layer 2 output neurons
    net = Net([784, 500, 500], "lif").to(device)

    total_dataset_epochs = 20

    # Lists to store the loss history globally
    history_layer_1 = []
    history_layer_2 = []


    print(f"Starting training for {total_dataset_epochs} epochs...")
    for epoch in range(total_dataset_epochs):
        # Wrap the loader in tqdm for estimated time tracking
        for x, y in tqdm(train_loader, desc=f"Epoch {epoch+1}/{total_dataset_epochs}"):
            x, y = x.to(device), y.to(device)

            x_pos = overlay_y_on_x(x, y)
            rnd = torch.randperm(x.size(0))
            x_neg = overlay_y_on_x(x, y[rnd])

            # Extract the loss numbers before the loop moves on
            batch_losses = net.train_network(x_pos, x_neg)

            history_layer_1.append(batch_losses[0][0])
            history_layer_2.append(batch_losses[1][0])


    print("Training complete. Running full evaluation...")

    # Test on the full test dataset
    correct = 0
    total = 0
    for x_te, y_te in tqdm(test_loader, desc="Testing"):
        x_te, y_te = x_te.to(device), y_te.to(device)
        predictions = net.predict(x_te)
        correct += predictions.eq(y_te).sum().item()
        total += y_te.size(0)

    print('Full Test error:', 100 * (1.0 - (correct / total)), '%')

    print("Saving model weights using safetensors...")
    save_model(net, "forward_forward_snn.safetensors")

    # Plot the saved data
    plt.plot(history_layer_1, label="Layer 1 Loss")
    plt.plot(history_layer_2, label="Layer 2 Loss")
    plt.xlabel("Training Steps (Batches)")
    plt.ylabel("Loss")
    plt.legend()
    plt.title("Forward-Forward Spiking Neural Network Loss")
    plt.savefig("ff_snn_loss.png")
    print("Saved plot to ff_snn_loss.png")
